use std::cell::RefCell;
use std::path::Path;
use std::path::PathBuf;

use logger::StdioLogger;
use logger_srcfile::WrapFileLogger;
use oxc_allocator::Allocator;
use oxc_semantic::SemanticBuilder;

use ast_segmenter::segment_info::Segment;

/// Per-worker-thread arena reused across `get_file_segments` calls.
///
/// Each Rayon worker borrows the arena, parses one file, extracts all owned
/// data, then calls `Allocator::reset()` (cheap — returns bumpalo chunks to
/// the free list without freeing the backing allocation).  This avoids the
/// overhead of creating a new `Allocator` for every file while keeping the
/// steady-state arena size bounded by the largest file each worker has seen.
thread_local! {
    static PARSE_ARENA: RefCell<Allocator> = RefCell::new(Allocator::default());
}

#[derive(Debug, thiserror::Error)]
pub enum SourceFileParseError {
    #[error("Auto-generated file")]
    AutogeneratedFile,
    #[error("Unable to load {0} file: {1}")]
    LoadFile(PathBuf, std::io::Error),
    #[error("TypeScript syntax error in {0}: {1}")]
    TypeScriptSyntax(PathBuf, String),
    #[error("Parser error in {0}: {1}")]
    Parser(PathBuf, String),
}

/// Parses a source file and returns per-statement segments via `ast_segmenter::segment_file`.
///
/// Uses a per-thread arena (`PARSE_ARENA`) so the backing allocation is reused
/// across calls on the same thread.  All returned data is fully owned; no
/// arena-lifetime references escape.
pub fn get_file_segments(file_path: &Path) -> Result<Vec<Segment>, SourceFileParseError> {
    let source = match std::fs::read_to_string(file_path) {
        Ok(s) => s,
        Err(e) => return Err(SourceFileParseError::LoadFile(file_path.to_path_buf(), e)),
    };

    if source.contains("// This file is auto-generated") {
        return Err(SourceFileParseError::AutogeneratedFile);
    }

    PARSE_ARENA.with(|arena_cell| {
        let arena = arena_cell.borrow();

        let ret = oxc_utils_parse::parse_file(&arena, &source, file_path);

        if ret.panicked || !ret.errors.is_empty() {
            let msgs = ret
                .errors
                .iter()
                .map(|e| e.to_string())
                .collect::<Vec<_>>()
                .join("\n");
            // Drop borrow before resetting so we don't hold two borrows.
            drop(arena);
            arena_cell.borrow_mut().reset();
            return Err(SourceFileParseError::TypeScriptSyntax(
                file_path.to_path_buf(),
                msgs,
            ));
        }

        let semantic = SemanticBuilder::new().build(&ret.program).semantic;
        let stdio_logger = StdioLogger::new();
        let filename = file_path.to_string_lossy();
        // Clone source so it can be owned by the logger while `ret` borrows from the arena.
        let logger = WrapFileLogger::new(filename, source.clone(), &stdio_logger);

        let segments = ast_segmenter::segment_file(&logger, &ret.program, &semantic);

        // All owned data is extracted; drop arena-lifetime values, then reset.
        drop(semantic);
        drop(ret);
        drop(arena);
        arena_cell.borrow_mut().reset();

        Ok(segments)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Verify that successive calls to `get_file_segments` on the same thread
    /// reuse the same `PARSE_ARENA` instance (no unbounded growth).
    ///
    /// After the first call the arena has been reset; the second call should
    /// reuse the already-allocated backing memory rather than growing.  We
    /// assert this by checking that `capacity()` after the second call
    /// is no larger than after the first — i.e. the arena is not doubling.
    #[test]
    fn test_arena_reused_across_calls() {
        let tmpdir = test_tmpdir::TmpDir::new();
        let file = tmpdir.root().join("a.ts");
        std::fs::write(&file, "export const x = 1;\n").unwrap();

        // First call — arena grows to fit the file.
        let _ = get_file_segments(&file);
        let capacity_after_first = PARSE_ARENA.with(|c| c.borrow().capacity());

        // Second call on the same thread — arena is reset and reused; its
        // capacity should stay ≤ the first call's value (same file).
        let _ = get_file_segments(&file);
        let capacity_after_second = PARSE_ARENA.with(|c| c.borrow().capacity());

        assert!(
            capacity_after_second <= capacity_after_first,
            "arena grew on second call ({capacity_after_second} > {capacity_after_first}); arena reset is not working"
        );
    }
}
